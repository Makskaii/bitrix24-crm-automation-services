import fs from "node:fs";
import path from "node:path";

import {
    config
} from "../config.js";

import {
    getDeal,
    getDocument,
    getRealEstate,
    getUser,
    uploadDocument,
    deleteDocument
} from "../bitrix.js";

import {
    logger
} from "../logger.js";

import {
    buildDocx,
    convertDocxToPdf
} from "../docx/document.js";

import {
    buildPropertyValues
} from "./resolver.js";

import {
    getAgentPhoto,
    getPropertyImages
} from "./files.js";

import {
    extractRealEstateIds,
    findDealFieldCode
} from "./selection.js";

const processing = new Set();
const uploadedDocumentIds = new Set();

function dealValue(deal, key) {
    const camelKey =
        key.toLowerCase().replace(
            /_([a-z])/g,
            (_, char) =>
                char.toUpperCase()
        );

    return (
        deal[key] ??
        deal[key.toUpperCase()] ??
        deal[camelKey] ??
        null
    );
}

function agentName(user) {
    const name = [
        user?.NAME,
        user?.LAST_NAME
    ]
        .filter(Boolean)
        .join(" ")
        .trim();

    return name
        ? name.toUpperCase()
        : "-";
}

function sanitize(value) {
    return String(value)
        .replace(/[<>:"/\\|?*\x00-\x1F]/g, "_")
        .trim();
}

async function buildRecords(
    ids,
    agent
) {
    const records = [];

    for (const id of ids) {
        const item =
            await getRealEstate(id);

        const [
            values,
            images
        ] = await Promise.all([
            buildPropertyValues(item),
            getPropertyImages(item)
        ]);

        records.push({
            values,
            images,
            agent
        });
    }

    return records;
}

export async function processDocumentEvent({
    documentId,
    entityTypeId,
    entityId
}) {
    if (uploadedDocumentIds.has(String(documentId))) {
        logger.info(
            "Document ignored: generated by handler",
            { documentId }
        );

        return;
    }

    if (processing.has(documentId)) {
        return;
    }

    processing.add(documentId);

    let generated = null;
    let pdf = null;

    try {
        if (Number(entityTypeId) !== 2) {
            return;
        }

        const document =
            await getDocument(
                documentId,
                entityTypeId,
                entityId
            );

        const template =
            config.templates[
            Number(document.templateId)
            ];

        if (!template) {
            logger.info(
                "Document ignored: unsupported template",
                {
                    documentId,
                    templateId:
                        document.templateId
                }
            );

            return;
        }

        const deal =
            await getDeal(
                Number(entityId)
            );

        const categoryId =
            Number(
                dealValue(
                    deal,
                    "CATEGORY_ID"
                )
            );

        if (
            !config.allowedCategories.has(
                categoryId
            )
        ) {
            logger.info(
                "Document ignored: unsupported category",
                {
                    documentId,
                    entityId,
                    categoryId
                }
            );

            return;
        }

        const fieldCode =
            await findDealFieldCode(
                template.fieldTitle
            );

        const relationValue =
            deal[fieldCode];

        const propertyIds =
            extractRealEstateIds(
                relationValue
            );

        if (!propertyIds.length) {
            throw new Error(
                `No Real Estate items selected in ${template.fieldTitle}`
            );
        }

        const assignedById =
            Number(
                dealValue(
                    deal,
                    "ASSIGNED_BY_ID"
                )
            );

        if (!assignedById) {
            throw new Error(
                "Deal has no assigned user"
            );
        }

        const user =
            await getUser(
                assignedById
            );

        const photo =
            await getAgentPhoto(user);

        const agent = {
            name: agentName(user),
            phone:
                user?.PERSONAL_MOBILE || "-",
            email:
                user?.EMAIL || "-",
            photo
        };

        const records =
            await buildRecords(
                propertyIds,
                agent
            );

        generated =
            await buildDocx(records);

        pdf = await convertDocxToPdf(
            generated.path
        );

        const fileName =
            sanitize(
                `${template.name}-${entityId}`
            )
                .replace(/\s+/g, "-") +
            ".docx";

        const uploaded = await uploadDocument(
            {
                entityId: Number(entityId),
                title:
                    document.title ||
                    template.name,
                number:
                    document.number ||
                    "",
                buffer: generated.buffer,
                pdfBuffer: pdf.buffer
            }
        );

        uploadedDocumentIds.add(
            String(uploaded.id)
        );

        await deleteDocument(documentId);

        logger.info(
            "Generated document replaced original",
            {
                dealId:
                    entityId,

                templateId:
                    document.templateId,

                originalDocumentId:
                    documentId,

                replacementDocumentId:
                    uploaded.id,

                pdfIncluded: true,

                propertyIds
            }
        );
    } catch (error) {
        let failedDocxPath = null;
        let diagnosticSaveError = null;

        if (generated?.path && fs.existsSync(generated.path)) {
            try {
                const failedDocxDir = path.resolve("failed-docx");

                fs.mkdirSync(failedDocxDir, {
                    recursive: true
                });

                failedDocxPath = path.join(
                    failedDocxDir,
                    `document-${documentId}.docx`
                );

                fs.copyFileSync(
                    generated.path,
                    failedDocxPath
                );
            } catch (saveError) {
                diagnosticSaveError =
                    saveError?.message ||
                    String(saveError);
            }
        }

        logger.error(
            "Document processing failed",
            {
                documentId,
                entityId,
                failedDocxPath,
                diagnosticSaveError,
                error:
                    error?.stack ||
                    error?.message ||
                    String(error)
            }
        );
    } finally {
        if (generated?.path) {
            fs.rmSync(
                generated.path,
                {
                    force: true
                }
            );
        }

        if (pdf?.path) {
            fs.rmSync(
                pdf.path,
                {
                    force: true
                }
            );
        }

        processing.delete(documentId);
    }
}
